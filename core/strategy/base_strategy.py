"""Base strategy — abstract class all strategies inherit from.

Every strategy implements three methods:
    on_market(snapshot) — called every bar with market data
    get_signals() — returns list of SignalEvents to trade
    on_fill(fill) — notified when a trade executes

Strategies emit *signals* (intent to trade), not orders. The risk
manager validates signals and converts approved ones to orders.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from datetime import datetime
from typing import Any

from loguru import logger

from core.events.event_bus import EventBus
from core.events.event_types import MarketEvent, FillEvent, SignalEvent
from data.models.market_snapshot import MarketSnapshot


class BaseStrategy(ABC):
    """Abstract base class for all trading strategies.

    Subclass this and implement on_market() and get_signals().

    Usage:
        class MyStrategy(BaseStrategy):
            def on_market(self, snapshot):
                # analyze the market
                if should_trade:
                    self.add_signal(SignalEvent(...))

            def get_signals(self):
                return self._pending_signals
    """

    def __init__(self, name: str, event_bus: EventBus | None = None):
        self.name = name
        self.event_bus = event_bus
        self._pending_signals: list[SignalEvent] = []
        self._current_timestamp: datetime | None = None
        self._bar_count = 0
        self._signal_count = 0

        # Subscribe to events if bus provided
        if self.event_bus:
            self.event_bus.subscribe(MarketEvent, self._handle_market)
            self.event_bus.subscribe(FillEvent, self._handle_fill)

    def _handle_market(self, event: MarketEvent) -> None:
        """Internal handler — wraps on_market with housekeeping."""
        self._current_timestamp = event.timestamp
        self._bar_count += 1
        self._pending_signals.clear()

        # Call the user's strategy logic
        self.on_market(event.snapshot)

        # Emit any signals the strategy generated
        signals = self.get_signals()
        if signals and self.event_bus:
            for signal in signals:
                signal.strategy_name = self.name
                signal.timestamp = event.timestamp
                self._signal_count += 1
                self.event_bus.emit(signal)

    def _handle_fill(self, event: FillEvent) -> None:
        """Internal handler — routes fills to on_fill if they belong to us."""
        if event.strategy_name == self.name:
            self.on_fill(event)

    @abstractmethod
    def on_market(self, snapshot: MarketSnapshot) -> None:
        """Called every bar with the latest market data.

        This is where your strategy logic lives. Analyze the snapshot,
        decide whether to trade, and call self.add_signal() if so.

        Args:
            snapshot: Complete market state at this timestamp.
        """
        ...

    def get_signals(self) -> list[SignalEvent]:
        """Return pending signals generated by on_market().

        Default implementation returns whatever was added via add_signal().
        Override if you need custom signal aggregation logic.
        """
        return list(self._pending_signals)

    def on_fill(self, event: FillEvent) -> None:
        """Called when one of this strategy's orders gets filled.

        Override to track positions, update state, etc.
        Default does nothing.
        """
        pass

    def add_signal(self, signal: SignalEvent) -> None:
        """Queue a signal for emission after on_market() returns."""
        self._pending_signals.append(signal)

    @property
    def bar_count(self) -> int:
        return self._bar_count

    @property
    def signal_count(self) -> int:
        return self._signal_count

    def __repr__(self) -> str:
        return f"Strategy({self.name}, bars={self._bar_count}, signals={self._signal_count})"
